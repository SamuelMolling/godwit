func TestExpandRefusesChangeTypeDependents(t *testing.T) {
	t.Parallel()
	for kind, tc := range changeTypeDependents {
		t.Run(kind, func(t *testing.T) {
			ddl := append([]string{depTable(tc.tbl)}, tc.ddl...)
			if tc.up != "" {
				ddl = tc.ddl
			}
			conn := newScratch(t, ddl...)
			up := tc.up
			if up == "" {
				up = "-- godwit: change-type " + tc.tbl + ".age bigint\n"
			}
			_, err := expandOne(t, conn, up, revertSentinel)
			if err == nil {
				t.Fatal("the swap would rebind this dependent to age_old; the expander must refuse")
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want %q", err, tc.want)
			}
			if !strings.Contains(err.Error(), "would silently keep reading") {
				t.Fatalf("the refusal must say why: %v", err)
			}
		})
	}
}

// TestChangeTypeSwapRebindsDependents is the hazard the refusal exists for, shown on PostgreSQL itself:
// the two renames of the contract phase move every dependent onto the retired column without an error.
func TestChangeTypeSwapRebindsDependents(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	conn := newScratch(t, depTable("swap"),
		`CREATE VIEW public.swap_v AS SELECT id, age FROM public.swap`,
		`CREATE INDEX swap_age_idx ON public.swap (age)`,
		`ALTER TABLE public.swap ADD CONSTRAINT swap_age_pos CHECK (age > 0)`,
	)
	for _, s := range []string{
		`ALTER TABLE public.swap ADD COLUMN age_new bigint`,
		`ALTER TABLE public.swap RENAME COLUMN age TO age_old`,
		`ALTER TABLE public.swap RENAME COLUMN age_new TO age`,
	} {
		if _, err := conn.Exec(ctx, s); err != nil {
			t.Fatalf("%s: %v", s, err)
		}
	}
	for probe, want := range map[string]string{
		`SELECT pg_get_viewdef('public.swap_v'::regclass)`:                                   "age_old",
		`SELECT pg_get_indexdef('public.swap_age_idx'::regclass)`:                            "age_old",
		`SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conname = 'swap_age_pos'`: "age_old",
		`SELECT format_type(atttypid, atttypmod) FROM pg_attribute
		   WHERE attrelid = 'public.swap'::regclass AND attname = 'age'`: "bigint",
	} {
		var got string
		if err := conn.QueryRow(ctx, probe).Scan(&got); err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(got, want) {
			t.Fatalf("%s = %q, want %q", probe, got, want)
		}
	}
}

