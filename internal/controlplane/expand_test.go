// flakyDB fails or rewrites the nth statement the expander runs, so every catalog probe's error branch
// is reachable without breaking the database itself.
type flakyDB struct {
	engine.DB
	n    *int
	fail int
	sub  string
}

type failRow struct{ err error }

func (r failRow) Scan(...any) error { return r.err }

func (f flakyDB) QueryRow(ctx context.Context, sql string, args ...any) pgx.Row {
	*f.n++
	if *f.n != f.fail {
		return f.DB.QueryRow(ctx, sql, args...)
	}
	if f.sub != "" {
		return f.DB.QueryRow(ctx, f.sub)
	}

	return failRow{errBoom}
}

func (f flakyDB) Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error) {
	*f.n++
	if *f.n != f.fail {
		return f.DB.Query(ctx, sql, args...)
	}
	if f.sub != "" {
		return f.DB.Query(ctx, f.sub)
	}

	return nil, errBoom
}

func (f flakyDB) Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error) {
	return f.DB.Exec(ctx, sql, args...)
}

