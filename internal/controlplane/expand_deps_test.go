// TestExpandChangeTypeCarriesTheDefault covers the one thing a rename loses that belongs to the column
// itself rather than to another object: godwit puts it back on the new column instead of refusing.
func TestExpandChangeTypeCarriesTheDefault(t *testing.T) {
	t.Parallel()
	conn := newScratch(t, usersDDL, `ALTER TABLE public.users ALTER COLUMN age SET DEFAULT 7`,
		`INSERT INTO public.users (email, age) VALUES ('a', 1)`)
	exp, err := expandOne(t, conn, changeAge, revertSentinel)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(exp.UpSQL, "ALTER TABLE public.users ALTER COLUMN age_new SET DEFAULT 7;") {
		t.Fatalf("expansion:\n%s", exp.UpSQL)
	}
	if !strings.Contains(strings.Join(exp.Notes, "\n"), "carries the default 7") {
		t.Fatalf("notes = %v", exp.Notes)
	}
	applyExpansion(t, conn, changeAge, revertSentinel, exp)
	var def string
	if err := conn.QueryRow(context.Background(), `
		SELECT pg_get_expr(ad.adbin, ad.adrelid) FROM pg_attrdef ad
		JOIN pg_attribute a ON a.attrelid = ad.adrelid AND a.attnum = ad.adnum
		WHERE ad.adrelid = 'public.users'::regclass AND a.attname = 'age'`).Scan(&def); err != nil {
		t.Fatalf("the swapped column kept no default: %v", err)
	}
	if def != "7" {
		t.Fatalf("default = %q", def)
	}
}

