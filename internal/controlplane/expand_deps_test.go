// depCase is one dependent kind bound to <tbl>.age and the fragment its refusal must name.
type depCase struct {
	tbl  string
	ddl  []string
	up   string
	want string
}

func depTable(name string) string {
	return fmt.Sprintf(`CREATE TABLE public.%s (
		id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		email text NOT NULL,
		age integer NOT NULL,
		price integer
	)`, name)
}

