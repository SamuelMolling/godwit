func TestExpandBackfill(t *testing.T) {
	t.Parallel()
	conn := newScratch(t,
		`CREATE TABLE public.t (k text PRIMARY KEY, a integer, b integer)`,
		`INSERT INTO public.t SELECT g::text, g, NULL FROM generate_series(1, 30) g`)
	up := "-- godwit: backfill t set='b = a * 2' where='b IS NULL' batch=7 pause=1ms\n"
	exp, err := expandOne(t, conn, up, "UPDATE public.t SET b = NULL;\n")
	if err != nil {
		t.Fatal(err)
	}
	if exp.Contract() != -1 || len(exp.Phase) != 1 || exp.Batches[0].Size != 7 || exp.Batches[0].Pause != time.Millisecond {
		t.Fatalf("phases %v batches %+v", exp.Phase, exp.Batches[0])
	}
	if !strings.Contains(exp.UpSQL, "$1::text") {
		t.Fatalf("text cursor:\n%s", exp.UpSQL)
	}
	applyExpansion(t, conn, up, "UPDATE public.t SET b = NULL;\n", exp)

	var done int
	if err := conn.QueryRow(context.Background(), `SELECT count(*) FROM public.t WHERE b = a * 2`).Scan(&done); err != nil {
		t.Fatal(err)
	}
	if done != 30 {
		t.Fatalf("%d of 30 rows backfilled", done)
	}
	if _, err := expandOne(t, conn, up, revertSentinel); err == nil || !strings.Contains(err.Error(), "no generated inverse") {
		t.Fatalf("backfill revert = %v", err)
	}
}

// TestExpandBackfillResumesAfterCrash kills the backfill between batches and re-applies it; the second
// pass must start from the journalled cursor and leave every row correct.
func TestExpandBackfillResumesAfterCrash(t *testing.T) {
	t.Parallel()
	ctx := context.Background()
	conn := newScratch(t,
		`CREATE TABLE public.t (k bigint PRIMARY KEY, a integer, b integer)`,
		`INSERT INTO public.t SELECT g, g, NULL FROM generate_series(1, 100) g`)
	up := "-- godwit: backfill t set='b = a * 2' where='b IS DISTINCT FROM a * 2' batch=10\n"
	down := "UPDATE public.t SET b = NULL;\n"
	exp, err := expandOne(t, conn, up, down)
	if err != nil {
		t.Fatal(err)
	}
	p, err := ExpandPlan(engine.Plan{Migration: directiveMigration(t, up, down), Direction: engine.DirectionUp}, exp)
	if err != nil {
		t.Fatal(err)
	}

	stop := make(chan struct{})
	crash := func(point engine.HookPoint, _ int) {
		if point == engine.HookAfterBatch {
			select {
			case <-stop:
			default:
				close(stop)
			}
		}
	}
	if _, err := applyPlans(ctx, conn, engine.Options{}, []engine.Plan{p}, nil, engine.WithHook(crash)); err != nil {
		t.Fatal(err)
	}

	var cursor *string
	var doneRows int64
	if err := conn.QueryRow(ctx,
		`SELECT cursor, rows_done FROM godwit.journal WHERE stmt_idx = 0 ORDER BY recorded_at DESC LIMIT 1`).
		Scan(&cursor, &doneRows); err != nil {
		t.Fatal(err)
	}
	if _, err := conn.Exec(ctx, `DELETE FROM godwit.migrations WHERE version = 20260101000000`); err != nil {
		t.Fatal(err)
	}
	if _, err := conn.Exec(ctx, `UPDATE public.t SET b = NULL WHERE k > 50`); err != nil {
		t.Fatal(err)
	}
	if _, err := applyPlans(ctx, conn, engine.Options{}, []engine.Plan{p}, nil); err != nil {
		t.Fatal(err)
	}
	var pending int
	if err := conn.QueryRow(ctx, `SELECT count(*) FROM public.t WHERE b IS DISTINCT FROM a * 2`).Scan(&pending); err != nil {
		t.Fatal(err)
	}
	if pending != 0 {
		t.Fatalf("%d rows left unbackfilled after resume", pending)
	}
}

func TestExpandRefusals(t *testing.T) {
	t.Parallel()
	conn := newScratch(t,
		usersDDL,
		`CREATE TABLE public.orders (id bigint PRIMARY KEY, user_id bigint REFERENCES public.users (id))`,
		`CREATE TABLE public.taken (id bigint PRIMARY KEY, age integer, age_new integer)`,
		`CREATE TABLE public.nokey (age integer, tag text)`,
		`CREATE TABLE public.gen (id bigint PRIMARY KEY, age integer, twice integer GENERATED ALWAYS AS (age * 2) STORED)`,
		`CREATE TABLE public.parted (id bigint, age integer) PARTITION BY RANGE (id)`,
		`CREATE TABLE public.ref (id bigint PRIMARY KEY, age integer)`,
		`CREATE TABLE public.child (rid bigint REFERENCES public.ref (id))`,
		`CREATE VIEW public.v AS SELECT id, email FROM public.users`,
		`CREATE FUNCTION public.noisy(integer) RETURNS integer LANGUAGE sql VOLATILE AS $$ SELECT $1 $$`,
	)
	for name, tc := range map[string]struct{ up, want string }{
		"missing table":     {"-- godwit: change-type ghost.age bigint\n", "does not exist in the schema"},
		"missing column":    {"-- godwit: change-type users.ghost bigint\n", "does not exist in the schema"},
		"view":              {"-- godwit: change-type v.email text\n", "is not an ordinary table"},
		"partitioned":       {"-- godwit: change-type parted.age bigint\n", "is partitioned"},
		"identity":          {"-- godwit: change-type users.id bigint\n", "is an identity column"},
		"generated":         {"-- godwit: change-type gen.twice bigint\n", "is a generated column"},
		"foreign key":       {"-- godwit: change-type orders.user_id integer\n", "takes part in a foreign key"},
		"referenced key":    {"-- godwit: change-type ref.id integer\n", "takes part in a foreign key"},
		"collision":         {"-- godwit: change-type taken.age bigint\n", "age_new already exists"},
		"no primary key":    {"-- godwit: change-type nokey.age bigint\n", "has no single-column primary key"},
		"unknown key":       {"-- godwit: change-type users.age bigint key=ghost\n", "does not exist on"},
		"nullable key":      {"-- godwit: change-type nokey.age bigint key=tag\n", "is nullable"},
		"non unique key":    {"-- godwit: change-type users.age bigint key=email\n", "no single-column unique btree index"},
		"volatile using":    {"-- godwit: change-type users.age bigint using='noisy(age)'\n", "VOLATILE function"},
		"subquery using":    {"-- godwit: change-type users.age bigint using='(SELECT 1)'\n", "contains a subquery"},
		"other table using": {"-- godwit: change-type users.age bigint using='orders.id'\n", "only columns of users"},
		"two directives":    {"-- godwit: change-type users.age bigint\n-- godwit: change-type users.age numeric\n", "already the subject"},
		"destructive sql":   {"ALTER TABLE public.users DROP COLUMN email;\n-- godwit: change-type users.age bigint\n", "H003 in its own SQL"},
		"split statement":   {"CREATE TABLE public.z (\n-- godwit: change-type users.age bigint\n a int);\n", "between whole statements"},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := expandOne(t, conn, tc.up, "SELECT 1;\n")
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("err = %v, want %q", err, tc.want)
			}
		})
	}
}

