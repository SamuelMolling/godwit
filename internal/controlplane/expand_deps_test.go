// TestExpandDropColumnKeepsWhatBelongsToTheColumn is the other half of the line droppable draws: an object
// that exists only for this column is meant to go with it.
func TestExpandDropColumnKeepsWhatBelongsToTheColumn(t *testing.T) {
	t.Parallel()
	conn := newScratch(t, depTable("own"),
		`CREATE INDEX own_age_idx ON public.own (age)`,
		`ALTER TABLE public.own ADD CONSTRAINT own_age_pos CHECK (age > 0)`,
		`ALTER TABLE public.own ALTER COLUMN age SET DEFAULT 3`,
		`CREATE SEQUENCE public.own_seq OWNED BY public.own.age`,
	)
	up := "-- godwit: drop-column own.age\n"
	exp, err := expandOne(t, conn, up, "SELECT 1;\n")
	if err != nil {
		t.Fatalf("an index, check, default and sequence of this column alone go with it: %v", err)
	}
	applyExpansion(t, conn, up, "SELECT 1;\n", exp)
	var n int
	if err := conn.QueryRow(context.Background(),
		`SELECT count(*) FROM pg_attribute WHERE attrelid = 'public.own'::regclass AND attname = 'age' AND NOT attisdropped`).
		Scan(&n); err != nil {
		t.Fatal(err)
	}
	if n != 0 {
		t.Fatalf("column count = %d", n)
	}
}

func TestDependentsProbeErrors(t *testing.T) {
	t.Parallel()
	conn := newScratch(t, depTable("probe"), `CREATE VIEW public.probe_v AS SELECT id, age FROM public.probe`)
	col := columnFacts{Schema: "public", Table: "probe", Column: "age"}
	n := 0
	if _, err := col.dependents(context.Background(), flakyDB{DB: conn, n: &n, fail: 1}); err == nil ||
		!strings.Contains(err.Error(), "inspect public.probe.age dependencies") {
		t.Fatalf("query err = %v", err)
	}
	n = 0
	if _, err := col.dependents(context.Background(), flakyDB{DB: conn, n: &n, fail: 1, sub: "SELECT 1"}); err == nil ||
		!strings.Contains(err.Error(), "read public.probe.age dependencies") {
		t.Fatalf("collect err = %v", err)
	}
	d := engine.Directive{Line: 1, Text: "godwit: drop-column probe.age"}
	n = 0
	if err := col.droppable(context.Background(), flakyDB{DB: conn, n: &n, fail: 1}, d); err == nil {
		t.Fatalf("droppable err = %v", err)
	}
}
